"""
XGBoost Match Outcome Prediction Model.

Gradient Boosted Trees for predicting Win / Draw / Loss.
Uses multi-class softprob objective for probability outputs.
"""

import logging
import os
from typing import Optional

import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, log_loss, f1_score

try:
    import xgboost as xgb
except ImportError:
    xgb = None

from django.conf import settings

logger = logging.getLogger(__name__)

# Outcome encoding
OUTCOME_MAP = {'home_win': 0, 'draw': 1, 'away_win': 2}
OUTCOME_LABELS = {v: k for k, v in OUTCOME_MAP.items()}


class XGBoostPredictor:
    """
    XGBoost multi-class classifier for match outcomes.

    Trained on historical features generated by FeatureEngineeringService.
    Outputs calibrated probabilities for home_win / draw / away_win.
    """

    DEFAULT_PARAMS = {
        'objective': 'multi:softprob',
        'num_class': 3,
        'max_depth': 6,
        'learning_rate': 0.05,
        'n_estimators': 500,
        'subsample': 0.8,
        'colsample_bytree': 0.8,
        'min_child_weight': 3,
        'gamma': 0.1,
        'reg_alpha': 0.1,
        'reg_lambda': 1.0,
        'eval_metric': 'mlogloss',
        'use_label_encoder': False,
        'random_state': 42,
        'n_jobs': -1,
    }

    def __init__(self, params: dict = None):
        if xgb is None:
            raise ImportError("xgboost is required. Install it with: pip install xgboost")
        self.params = {**self.DEFAULT_PARAMS, **(params or {})}
        self.model: Optional[xgb.XGBClassifier] = None
        self.feature_names: list[str] = []
        self.training_metrics: dict = {}

    # ── Training ────────────────────────────────

    def train(self, X: pd.DataFrame, y: pd.Series, test_size: float = 0.2) -> dict:
        """
        Train the XGBoost model on feature matrix X and outcome labels y.

        Args:
            X: Feature DataFrame
            y: Series of outcomes ('home_win', 'draw', 'away_win')
            test_size: Validation split ratio

        Returns:
            Training metrics dict
        """
        y_encoded = y.map(OUTCOME_MAP)
        self.feature_names = list(X.columns)

        X_train, X_val, y_train, y_val = train_test_split(
            X, y_encoded, test_size=test_size, random_state=42, stratify=y_encoded,
        )

        self.model = xgb.XGBClassifier(**self.params)
        self.model.fit(
            X_train, y_train,
            eval_set=[(X_val, y_val)],
            verbose=False,
        )

        # Evaluate
        y_pred = self.model.predict(X_val)
        y_prob = self.model.predict_proba(X_val)

        self.training_metrics = {
            'accuracy': round(accuracy_score(y_val, y_pred), 4),
            'log_loss': round(log_loss(y_val, y_prob), 4),
            'f1_weighted': round(f1_score(y_val, y_pred, average='weighted'), 4),
            'samples_train': len(X_train),
            'samples_val': len(X_val),
            'features_count': len(self.feature_names),
        }

        logger.info(f"XGBoost trained: {self.training_metrics}")
        return self.training_metrics

    # ── Prediction ──────────────────────────────

    def predict(self, features: dict) -> dict:
        """
        Predict match outcome probabilities from a feature dict.

        Returns:
            {
                'home_win_prob': float,
                'draw_prob': float,
                'away_win_prob': float,
                'predicted_outcome': str,
                'confidence': float,
            }
        """
        if self.model is None:
            raise RuntimeError("Model not trained or loaded. Call train() or load() first.")

        # Build feature vector aligned to training columns
        feature_vector = pd.DataFrame([features])
        for col in self.feature_names:
            if col not in feature_vector.columns:
                feature_vector[col] = 0.0
        feature_vector = feature_vector[self.feature_names]

        probs = self.model.predict_proba(feature_vector)[0]
        predicted_class = int(np.argmax(probs))

        return {
            'home_win_prob': round(float(probs[0]), 4),
            'draw_prob': round(float(probs[1]), 4),
            'away_win_prob': round(float(probs[2]), 4),
            'predicted_outcome': OUTCOME_LABELS[predicted_class],
            'confidence': round(float(np.max(probs)) * 100, 2),
        }

    # ── Feature Importance ──────────────────────

    def get_feature_importance(self, top_n: int = 15) -> list[dict]:
        """Return top N most important features."""
        if self.model is None:
            return []

        importance = self.model.feature_importances_
        indices = np.argsort(importance)[::-1][:top_n]

        return [
            {'feature': self.feature_names[i], 'importance': round(float(importance[i]), 4)}
            for i in indices
        ]

    # ── Persistence ─────────────────────────────

    def save(self, filepath: str) -> None:
        """Save model and metadata to disk."""
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        joblib.dump({
            'model': self.model,
            'feature_names': self.feature_names,
            'params': self.params,
            'metrics': self.training_metrics,
        }, filepath)
        logger.info(f"XGBoost model saved to {filepath}")

    def load(self, filepath: str) -> None:
        """Load model from disk."""
        data = joblib.load(filepath)
        self.model = data['model']
        self.feature_names = data['feature_names']
        self.params = data['params']
        self.training_metrics = data.get('metrics', {})
        logger.info(f"XGBoost model loaded from {filepath}")
